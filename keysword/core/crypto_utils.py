"""Cryptographic utility functions."""

from Crypto.Hash import HMAC, SHA256


class DeterministicRandom:
    """Deterministic random number generator for RSA key generation."""
    
    def __init__(self, seed):
        """
        Initialize with a seed.
        
        Args:
            seed: bytes - seed for deterministic generation
        """
        self.seed = seed
        self.counter = 0

    def read(self, n):
        """
        Generate n random bytes deterministically.
        
        Args:
            n: int - number of bytes to generate
            
        Returns:
            bytes: n deterministically generated bytes
        """
        output = bytearray()
        while len(output) < n:
            counter_bytes = self.counter.to_bytes(8, 'big')
            h = HMAC.new(self.seed, counter_bytes, digestmod=SHA256)
            output.extend(h.digest())
            self.counter += 1
        return bytes(output[:n])

